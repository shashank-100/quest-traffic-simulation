/**
 * Serializable scenario model. A scenario fully describes a reproducible experiment:
 * road network + signal plans + traffic demand + seed. Units are SI (metres, seconds, m/s).
 */

export type Level = 0 | 1;
export type DriveSide = 'left' | 'right';
export type VehicleType = 'car' | 'bus' | 'bike' | 'truck';

export const VEHICLE_TYPES: readonly VehicleType[] = ['car', 'bus', 'bike', 'truck'];

export interface PhaseDef {
  /** Seconds of green for this phase. */
  green: number;
  /** Road ids whose traffic arriving at this node receives green in this phase. */
  approaches: string[];
}

export interface SignalDef {
  enabled: boolean;
  phases: PhaseDef[];
  yellow: number;
  allRed: number;
  /** Cycle offset in seconds, for coordinating neighbouring signals. */
  offset: number;
}

export interface NodeDef {
  id: string;
  x: number;
  y: number;
  /** 0 = ground, 1 = elevated (flyover deck). Roads only meet where they share a node. */
  level: Level;
  signal?: SignalDef;
}

export interface RoadDef {
  id: string;
  name?: string;
  from: string;
  to: string;
  /** Lanes travelling from → to. */
  lanesFwd: number;
  /** Lanes travelling to → from. 0 makes the road one-way. */
  lanesBwd: number;
  laneWidth: number;
  /** m/s */
  speedLimit: number;
}

export type VehicleMix = Record<VehicleType, number>;

export interface FlowDef {
  id: string;
  name?: string;
  /** Entry endpoint node id. */
  origin: string;
  /** Exit endpoint node id, or null for "any reachable exit". */
  destination: string | null;
  /** Mean arrival rate in vehicles per hour (Poisson arrivals). */
  rate: number;
  mix: VehicleMix;
  /** Multiplier on each vehicle type's nominal desired speed. */
  speedFactor: number;
  start: number;
  end: number;
  /** Optional cap on vehicles generated by this flow. */
  maxVehicles?: number;
  /** Junctions (node ids) every vehicle of this flow must pass through, in order. */
  via?: string[];
}

export interface Scenario {
  id: string;
  name: string;
  description?: string;
  seed: number;
  /** Default run length in seconds for headless runs and comparisons. */
  duration: number;
  driveSide: DriveSide;
  /** When true, new vehicles are routed by observed travel times rather than free-flow times. */
  congestionAwareRouting: boolean;
  nodes: NodeDef[];
  roads: RoadDef[];
  flows: FlowDef[];
}
